def main() -> None:
    wb = Workbook()
    ws = wb.active
    ws.title = "Фулфилменты"

    header_font = Font(bold=True, color="FFFFFF", size=11)
    header_fill = PatternFill("solid", fgColor="2F5496")
    header_align = Alignment(horizontal="center", vertical="center", wrap_text=True)
    cell_align = Alignment(vertical="top", wrap_text=True)
    thin = Border(
        left=Side(style="thin", color="B0B0B0"),
        right=Side(style="thin", color="B0B0B0"),
        top=Side(style="thin", color="B0B0B0"),
        bottom=Side(style="thin", color="B0B0B0"),
    )

    for col, header in enumerate(HEADERS, 1):
        cell = ws.cell(1, col, header)
        cell.font = header_font
        cell.fill = header_fill
        cell.alignment = header_align
        cell.border = thin

    for row_idx, row in enumerate(ROWS, 2):
        region = row[1]
        fill = PatternFill("solid", fgColor=REGION_FILLS.get(region, "FFFFFF"))
        for col, value in enumerate(row, 1):
            cell = ws.cell(row_idx, col, value)
            cell.alignment = cell_align
            cell.border = thin
            cell.fill = fill
            if col == 1:
                cell.alignment = Alignment(horizontal="center", vertical="top")

    widths = {
        "A": 6,
        "B": 22,
        "C": 38,
        "D": 55,
        "E": 42,
        "F": 55,
        "G": 55,
        "H": 42,
    }
    for col, width in widths.items():
        ws.column_dimensions[col].width = width

    ws.row_dimensions[1].height = 28
    for i in range(2, len(ROWS) + 2):
        ws.row_dimensions[i].height = 55

    ws.auto_filter.ref = f"A1:H{len(ROWS) + 1}"
    ws.freeze_panes = "A2"

    # Summary sheet by region
    summary = wb.create_sheet("Сводка по регионам")
    summary_headers = ["Регион", "Кол-во", "С ценой", "Без цены / неизвестно"]
    for col, header in enumerate(summary_headers, 1):
        cell = summary.cell(1, col, header)
        cell.font = header_font
        cell.fill = header_fill
        cell.alignment = header_align
        cell.border = thin

    from collections import Counter, defaultdict

    by_region = defaultdict(list)
    for row in ROWS:
        by_region[row[1]].append(row)

    unknown_markers = ("не названа", "неизвестно", "не указан")
    r = 2
    for region in [
        "Москва и МО",
        "Санкт-Петербург и ЛО",
        "Казань",
        "Новосибирск",
        "Самара",
        "Владимир",
        "Мультирегиональные",
    ]:
        items = by_region[region]
        with_price = sum(
            1
            for item in items
            if not any(m in item[7].lower() for m in unknown_markers)
        )
        without = len(items) - with_price
        values = [region, len(items), with_price, without]
        fill = PatternFill("solid", fgColor=REGION_FILLS.get(region, "FFFFFF"))
        for col, value in enumerate(values, 1):
            cell = summary.cell(r, col, value)
            cell.border = thin
            cell.fill = fill
            cell.alignment = Alignment(vertical="center")
        r += 1

    for col, width in enumerate([24, 12, 12, 24], 1):
        summary.column_dimensions[get_column_letter(col)].width = width

    note = wb.create_sheet("Примечание")
    note["A1"] = "Каталог фулфилмент-операторов"
    note["A1"].font = Font(bold=True, size=14)
    note["A2"] = (
        "Данные собраны из исходного списка. № 65 в исходнике отсутствует "
        "(после 64 сразу идут 66–73). Фильтры включены на листе «Фулфилменты»."
    )
    note["A2"].alignment = Alignment(wrap_text=True)
    note.column_dimensions["A"].width = 100
    note.row_dimensions[2].height = 45

    out = "/workspace/fulfillment_catalog.xlsx"
    wb.save(out)
    print(f"Saved {out} ({len(ROWS)} rows)")


if __name__ == "__main__":
    main()
